/* Kiểm thử scripts/chay-sql.mjs — bước TỰ CHẠY SQL lúc deploy — trên Postgres thật.
 *
 * Script ấy chạy không người trông lên database đang phục vụ khách, nên từng
 * lời hứa của nó phải được chứng minh chứ không phải tin:
 *   · chạy đúng một lần cho mỗi phiên bản nội dung, deploy sau không đụng database;
 *   · nội dung đổi thì chạy lại;
 *   · hỏng một câu là rollback TOÀN BỘ, thoát khác 0 (để deploy dừng), có ghi lại;
 *   · không bao giờ in mật khẩu;
 *   · gói cap-nhat.sql thật chạy được qua đúng đường này.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dungPostgres } from "./pg-tam.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SCRIPT = join(ROOT, "scripts", "chay-sql.mjs");

let fail = 0;
const ok = (c, m) => {
  if (c) console.log(`  ✓ ${m}`);
  else {
    fail++;
    console.log(`  ✗ ${m}`);
  }
};

const pg = dungPostgres({ port: "5463" });
if (!pg.ok) {
  console.log(`⏭  BỎ QUA: ${pg.lyDo}`);
  process.exit(0);
}

const MAT_KHAU = "bi-mat-Kh0ng:duoc@in/ra";
/** Chạy script với chuỗi kết nối tới db (kèm một mật khẩu giả để kiểm việc che). */
function chay(db, args = [], { url } = {}) {
  const u = url ?? pg.url(db).replace("postgres@localhost", `postgres:${encodeURIComponent(MAT_KHAU)}@localhost`);
  const env = { ...process.env, SUPABASE_DB_URL: u };
  delete env.GITHUB_STEP_SUMMARY;
  const r = spawnSync("node", [SCRIPT, ...args], { env, encoding: "utf8" });
  return { code: r.status, out: (r.stdout || "") + (r.stderr || "") };
}
const sha = (f) => createHash("sha256").update(readFileSync(f)).digest("hex");

const tam = mkdtempSync(join(tmpdir(), "mstudo-chay-sql-"));
process.on("exit", () => rmSync(tam, { recursive: true, force: true }));
const FILE = join(tam, "cap-nhat.sql");

console.log("\n── Thiếu SUPABASE_DB_URL thì bỏ qua, không làm hỏng deploy ──");
{
  const env = { ...process.env };
  delete env.SUPABASE_DB_URL;
  const r = spawnSync("node", [SCRIPT], { env, encoding: "utf8" });
  ok(r.status === 0 && /bỏ qua/i.test(r.stdout), "thoát 0 và nói rõ là bỏ qua");
}
{
  const r = chay("x", [], { url: "day-khong-phai-url" });
  ok(r.code === 1 && /không đúng dạng/.test(r.out), "chuỗi kết nối sai dạng → thoát 1 kèm hướng dẫn");
}

console.log("\n── Luồng theo phiên bản nội dung (file giả) ──");
pg.newDb("nho");
pg.q(
  "nho",
  `create table public.system_runs (
     id bigint generated by default as identity primary key,
     kind text not null, name text not null, ok boolean not null,
     detail jsonb, duration_ms integer, started_at timestamptz not null default now());`,
);
const dem = (dk = "") => pg.q("nho", `select count(*) from public.system_runs where kind='sql' and name='cap-nhat.sql' ${dk}`);

writeFileSync(
  FILE,
  `-- bản 1; có chuỗi $$ lồng và dấu ; trong chuỗi
create table if not exists public.thu_a (id int primary key, ghi text);
insert into public.thu_a values (1, 'a;b') on conflict do nothing;
do $$ begin perform 1; end $$;
create or replace function public.thu_f() returns int language sql as $f$ select 1; $f$;
-- dòng cuối là chú thích không xuống dòng`,
);
let r = chay("nho", ["--file", FILE]);
ok(r.code === 0 && /Đã chạy xong/.test(r.out), "lần đầu: chạy và thoát 0");
ok(pg.q("nho", "select ghi from public.thu_a") === "a;b", "SQL đã thật sự chạy");
ok(dem("and ok") === "1", "ghi đúng một dòng thành công vào system_runs");
ok(pg.q("nho", "select detail->>'sha256' from public.system_runs") === sha(FILE), "dòng ghi mang sha256 của file");
ok(pg.q("nho", "select (duration_ms >= 0)::text from public.system_runs") === "true", "có ghi thời gian chạy");
ok(!r.out.includes(MAT_KHAU), "không in mật khẩu");

r = chay("nho", ["--file", FILE]);
ok(r.code === 0 && /không có SQL mới/.test(r.out), "lần hai cùng nội dung: không chạy lại");
ok(dem() === "1", "không ghi thêm dòng nào");

writeFileSync(FILE, readFileSync(FILE, "utf8") + "\ncreate table if not exists public.thu_b (id int);\n");
r = chay("nho", ["--file", FILE, "--kiem-tra"]);
ok(r.code === 0 && /CÓ SQL mới/.test(r.out), "--kiem-tra: báo có SQL mới");
ok(pg.q("nho", "select to_regclass('public.thu_b') is null") === "t", "--kiem-tra không chạy gì");
r = chay("nho", ["--file", FILE]);
ok(r.code === 0 && pg.q("nho", "select to_regclass('public.thu_b') is not null") === "t", "nội dung đổi: chạy lại");
ok(dem("and ok") === "2", "ghi dòng thứ hai");

console.log("\n── Hỏng giữa chừng: rollback hết, thoát khác 0, có ghi lại ──");
const banTot = readFileSync(FILE, "utf8");
writeFileSync(FILE, banTot + "create table public.thu_c (id int);\ninsert into public.thu_a values (2, 'x');\nselect 1/0;\ncreate table public.thu_d (id int);\n");
r = chay("nho", ["--file", FILE]);
ok(r.code === 1, "thoát 1 (deploy sẽ dừng)");
ok(/division by zero/.test(r.out) && /rollback/i.test(r.out), "in ra lỗi của Postgres và nói đã rollback");
ok(pg.q("nho", "select to_regclass('public.thu_c') is null and to_regclass('public.thu_d') is null") === "t", "bảng tạo trước câu hỏng đã bị rollback");
ok(pg.q("nho", "select count(*) from public.thu_a") === "1", "dữ liệu chèn trước câu hỏng đã bị rollback");
ok(dem("and not ok") === "1" && /division by zero/.test(pg.q("nho", "select detail->>'error' from public.system_runs where not ok")), "ghi một dòng HỎNG kèm câu lỗi");
ok(!r.out.includes(MAT_KHAU), "không in mật khẩu khi hỏng");
{
  // Câu lỗi phải chỉ đúng dòng của file (phần mở đầu không làm lệch số dòng).
  writeFileSync(FILE, "-- dòng 1\n-- dòng 2\nselect * from public.khong_co_bang_nay;\n");
  const r2 = chay("nho", ["--file", FILE]);
  ok(r2.code === 1 && /LINE 3:/.test(r2.out), "câu lỗi chỉ đúng số dòng trong file");
}
writeFileSync(FILE, banTot);
r = chay("nho", ["--file", FILE]);
ok(r.code === 0 && /không có SQL mới/.test(r.out), "bản tốt gần nhất vẫn được coi là đã chạy (dòng hỏng không tính)");

console.log("\n── Database chưa có bảng system_runs ──");
pg.newDb("trong");
writeFileSync(FILE, "create table if not exists public.thu_a (id int);\n");
r = chay("trong", ["--file", FILE]);
ok(r.code === 0 && /chưa ghi được dấu/.test(r.out), "vẫn chạy được, nói rõ là chưa ghi được dấu");
r = chay("trong", ["--file", FILE]);
ok(r.code === 0 && /Đã chạy xong/.test(r.out), "lần sau chạy lại (vô hại vì SQL chạy lại được)");

console.log("\n── Gói cap-nhat.sql THẬT qua đúng đường này ──");
pg.newDb("that");
pg.runFile("that", pg.supa("setup-all.sql"));
// Giống database đang chạy trước bản này: chưa từng có bảng ghi dấu.
pg.q("that", "drop table if exists public.system_runs cascade");
r = chay("that");
ok(r.code === 0 && /Đã chạy xong cap-nhat\.sql/.test(r.out), `cap-nhat.sql chạy được trong một lượt${r.code ? `\n${r.out.slice(-600)}` : ""}`);
ok(
  pg.q("that", "select count(*) from public.system_runs where kind='sql' and name='cap-nhat.sql' and ok") === "1",
  "cap-nhat.sql tự tạo bảng system_runs và lượt chạy đầu đã được ghi dấu",
);
r = chay("that");
ok(r.code === 0 && /không có SQL mới/.test(r.out), "lượt deploy kế tiếp không đụng database");

pg.stop();
if (fail) {
  console.log(`\n✗ ${fail} kiểm tra hỏng`);
  process.exit(1);
}
console.log("\n✓ chay-sql: tất cả đạt");
