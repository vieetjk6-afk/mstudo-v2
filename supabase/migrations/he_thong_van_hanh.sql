-- ============================================================================
-- Sức khoẻ hệ thống — nhật ký VẬN HÀNH để admin có một chỗ trả lời câu "đêm
-- qua mọi thứ có chạy không, cái gì đang hỏng".
--
-- Vì sao: các việc tự động chạy đêm (vercel.json → /api/cron/*) hỏng trong im
-- lặng, lỗi máy chủ chỉ nằm ở log Vercel không ai đọc, và gói Supabase Free có
-- trần cứng (database 500 MB, file 1 GB) đã từng khoá project một lần.
--
-- Mô hình:
--   • system_runs   — MỖI LƯỢT CHẠY một dòng. kind = 'cron' (src/lib/
--     system-runs.ts ghi sau mỗi lượt cron), 'sql' (scripts/chay-sql.mjs ghi
--     lúc deploy, detail = {sha256, git_sha, error?}), 'deploy', và 'alert'
--     (dấu "đã nhắc admin về việc quá hạn" — để mỗi ngày chỉ nhắc một lần).
--   • system_errors — lỗi GỘP: một dòng cho mỗi (chữ ký lỗi, ngày) kèm bộ đếm.
--     Chữ ký = băm của tên lỗi + dòng đầu thông báo (đã bỏ số / uuid) + đường
--     dẫn route, nên một lỗi lặp nghìn lần vẫn là một dòng. KHÔNG lưu thân
--     request, cookie, token hay query string.
--   • log_system_error()  — cộng dồn trong MỘT câu, báo lại lỗi này có MỚI
--     không (chưa gặp trong 7 ngày qua) để app chỉ nhắc admin lần đầu.
--   • system_run_state()  — lượt gần nhất + lượt TỐT gần nhất của từng việc.
--   • system_stats()      — dung lượng database, các bảng lớn nhất, từng bucket.
--   • prune_system_logs() — giữ bảng nhỏ: lượt chạy 60 ngày, lỗi 30 ngày.
--
-- Chỉ máy chủ (service-role) đụng tới: bật RLS, KHÔNG policy, thu hết quyền
-- của anon / authenticated. Không FORCE RLS — scripts/chay-sql.mjs ghi bằng
-- tài khoản chủ bảng (postgres).
--
-- Chạy trên Supabase SQL Editor. An toàn khi chạy lại (idempotent).
-- ============================================================================

create table if not exists public.system_runs (
  id          bigint generated by default as identity primary key,
  kind        text not null,              -- 'cron' | 'sql' | 'deploy'
  name        text not null,              -- 'reminders', 'zalo:money', 'backup', 'cap-nhat.sql'…
  ok          boolean not null,
  detail      jsonb,                      -- tóm tắt kết quả / câu lỗi (nhỏ, ≤ ~2 KB)
  duration_ms integer,
  started_at  timestamptz not null default now()
);

alter table public.system_runs enable row level security;

create table if not exists public.system_errors (
  signature  text not null,               -- băm do app tính (≤ 64 ký tự)
  day        date not null default ((now() at time zone 'utc')::date),
  source     text not null,               -- 'server' | 'client'
  message    text not null,               -- đã cắt ngắn
  path       text,                        -- route / đường dẫn, KHÔNG kèm query string
  sample     jsonb,                       -- mẫu nhỏ: dòng đầu stack, method, digest
  count      integer not null default 1,
  first_seen timestamptz not null default now(),
  last_seen  timestamptz not null default now(),
  primary key (signature, day)
);

alter table public.system_errors enable row level security;

create index if not exists system_runs_kind_name_idx on public.system_runs (kind, name, started_at desc);

create index if not exists system_errors_last_seen_idx on public.system_errors (last_seen desc);

-- Ghi một lỗi: cộng dồn vào dòng (chữ ký, hôm nay) trong MỘT câu, rồi báo lại
-- { count, is_new }. is_new = dòng vừa được TẠO và 7 ngày trước đó không có
-- dòng nào cùng chữ ký — tức là lỗi admin chưa từng được nhắc.
-- Cắt chuỗi ngay tại đây: hàm là hàng rào cuối, không tin độ dài app gửi.
create or replace function public.log_system_error(
  p_signature text,
  p_source    text,
  p_message   text,
  p_path      text default null,
  p_sample    jsonb default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_day   date := (now() at time zone 'utc')::date;
  v_sig   text := left(coalesce(p_signature, ''), 64);
  v_count integer;
  v_new   boolean;
begin
  if v_sig = '' then
    return jsonb_build_object('count', 0, 'is_new', false);
  end if;

  insert into public.system_errors as e (signature, day, source, message, path, sample)
  values (
    v_sig,
    v_day,
    case when p_source = 'client' then 'client' else 'server' end,
    left(coalesce(p_message, ''), 500),
    left(split_part(coalesce(p_path, ''), '?', 1), 300),
    case when p_sample is null or length(p_sample::text) > 2000 then null else p_sample end
  )
  on conflict (signature, day) do update
    set count     = e.count + 1,
        last_seen = now()
  returning e.count into v_count;

  v_new := v_count = 1 and not exists (
    select 1 from public.system_errors o
    where o.signature = v_sig and o.day < v_day and o.day >= v_day - 7
  );

  -- Dọn dần ở ~2% lượt gọi — không cần cron riêng cho bảng lỗi.
  if random() < 0.02 then
    delete from public.system_errors where day < v_day - 30;
  end if;

  return jsonb_build_object('count', v_count, 'is_new', v_new);
end;
$$;

-- Lượt GẦN NHẤT của từng (kind, name), kèm mốc lượt TỐT gần nhất, và mốc lượt
-- chạy đầu tiên còn lưu (để việc chưa từng chạy không đỏ ngay ngày đầu cài).
-- Một lần gọi là đủ cho cả trang Sức khoẻ lẫn luật "quá hạn".
create or replace function public.system_run_state()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'first_run_at', (select min(started_at) from public.system_runs where kind = 'cron'),
    'runs', coalesce((
      select jsonb_agg(to_jsonb(t))
      from (
        select distinct on (r.kind, r.name)
          r.kind, r.name, r.ok, r.detail, r.duration_ms, r.started_at,
          (select max(o.started_at) from public.system_runs o
            where o.kind = r.kind and o.name = r.name and o.ok) as last_ok_at
        from public.system_runs r
        order by r.kind, r.name, r.started_at desc, r.id desc
      ) t
    ), '[]'::jsonb)
  );
$$;

-- Dung lượng: database, ~15 bảng lớn nhất (mọi schema) (số dòng là ƯỚC LƯỢNG của
-- pg_class.reltuples — không đếm thật, đếm thật trên bảng lớn là tốn), và từng
-- bucket Storage. Project không có schema storage thì trả mảng rỗng, không lỗi.
create or replace function public.system_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_buckets jsonb := '[]'::jsonb;
  v_tables  jsonb;
begin
  select coalesce(jsonb_agg(to_jsonb(t)), '[]'::jsonb) into v_tables
  from (
    -- MỌI schema chứ không chỉ public: thủ phạm làm đầy database trên gói Free
    -- hay nằm ở bảng nhật ký của chính Supabase (auth.audit_log_entries,
    -- cron.job_run_details, net._http_response…) — chỉ nhìn public thì không
    -- bao giờ thấy. Bảng ngoài public hiện kèm tên schema.
    select case when n.nspname = 'public' then c.relname else n.nspname || '.' || c.relname end as name,
           pg_total_relation_size(c.oid) as bytes,
           greatest(c.reltuples, 0)::bigint as rows
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where c.relkind in ('r', 'm')
      and n.nspname not in ('pg_catalog', 'information_schema', 'pg_toast')
      and n.nspname not like 'pg_temp%'
    order by pg_total_relation_size(c.oid) desc
    limit 15
  ) t;

  if to_regclass('storage.objects') is not null then
    begin
      execute $q$
        select coalesce(jsonb_agg(to_jsonb(b)), '[]'::jsonb)
        from (
          select bucket_id as bucket,
                 count(*) as objects,
                 coalesce(sum(case when metadata->>'size' ~ '^[0-9]+$' then (metadata->>'size')::bigint else 0 end), 0) as bytes
          from storage.objects
          group by bucket_id
          order by 3 desc
        ) b
      $q$ into v_buckets;
    exception when others then
      v_buckets := '[]'::jsonb; -- storage đổi cấu trúc thì vẫn trả phần còn lại
    end;
  end if;

  return jsonb_build_object(
    'db_bytes', pg_database_size(current_database()),
    'tables', v_tables,
    'buckets', v_buckets,
    'storage_bytes', coalesce((select sum((x->>'bytes')::bigint) from jsonb_array_elements(v_buckets) x), 0)
  );
end;
$$;

-- Giữ bảng nhỏ. Lượt chạy: bỏ dòng quá 60 ngày NHƯNG giữ lượt gần nhất và lượt
-- tốt gần nhất của từng việc — scripts/chay-sql.mjs dựa vào dòng 'sql' tốt gần
-- nhất để biết gói SQL đã chạy chưa, mất nó là lần deploy sau chạy lại cả gói.
create or replace function public.prune_system_logs()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_runs integer;
  v_errs integer;
  v_n    integer;
  v_more integer := 0;
begin
  delete from public.system_runs r
  where r.started_at < now() - interval '60 days'
    and exists (
      select 1 from public.system_runs n
      where n.kind = r.kind and n.name = r.name
        and (n.started_at, n.id) > (r.started_at, r.id)
        and (n.ok or not r.ok)
    );
  get diagnostics v_runs = row_count;

  delete from public.system_errors where day < (now() at time zone 'utc')::date - 30;
  get diagnostics v_errs = row_count;

  -- Thông báo studio ĐÃ ĐỌC quá 180 ngày: không màn nào hiện lại (chuông chỉ
  -- lấy vài chục cái mới nhất) mà bảng cứ dài mãi. Chưa đọc thì giữ nguyên.
  begin
    delete from public.studio_notifications
    where read and not coalesce(important, false) and created_at < now() - interval '180 days';
    get diagnostics v_n = row_count;
    v_more := v_more + v_n;
  exception when others then null;
  end;

  -- Nhật ký nội bộ của Supabase — không ai đọc, tự phình không giới hạn và
  -- tính vào trần 500 MB. Mỗi khối bọc riêng: extension chưa bật hoặc không đủ
  -- quyền thì bỏ qua, không làm hỏng phần dọn ở trên.
  if to_regclass('cron.job_run_details') is not null then
    begin
      execute $q$delete from cron.job_run_details where end_time < now() - interval '7 days'$q$;
      get diagnostics v_n = row_count;
      v_more := v_more + v_n;
    exception when others then null;
    end;
  end if;
  if to_regclass('net._http_response') is not null then
    begin
      execute $q$delete from net._http_response where created < now() - interval '1 day'$q$;
      get diagnostics v_n = row_count;
      v_more := v_more + v_n;
    exception when others then null;
    end;
  end if;
  if to_regclass('auth.audit_log_entries') is not null then
    begin
      execute $q$delete from auth.audit_log_entries where created_at < now() - interval '30 days'$q$;
      get diagnostics v_n = row_count;
      v_more := v_more + v_n;
    exception when others then null;
    end;
  end if;

  return v_runs + v_errs + v_more;
end;
$$;

